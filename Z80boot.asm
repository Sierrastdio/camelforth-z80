; ============================================================================
; Z80 CamelForth Bootloader for 12KB EEPROM + 32KB RAM Memory Map
; 
; [Memory Map]
; 0000H - 2FFFH : EEPROM #1~#6 (12KB)
; 4000H - BFFFH : 62256 RAM (32KB)
; ============================================================================

    org 0000h

RESET:
    di                  ; 인터럽트 비활성화
    ld sp, 0C000h       ; 스택 포인터 설정 (RAM 최상단 BFFFH부터 아래로 사용)

    ld hl, IMG_START    ; ROM 내 CamelForth 이미지 시작 위치 (0020H)
    ld de, 4000h        ; RAM 시작 위치 (4000H)
    ld bc, 2FE0h        ; 복사할 크기 (12KB - 32바이트 = 12,256 바이트)
    ldir                ; ROM -> RAM 데이터 블록 복사

    jp 4000h            ; RAM으로 복사된 CamelForth 실행

    ; ------------------------------------------------------------------------
    ; 부트로더 크기를 정확히 32바이트(0020H)로 맞추기 위한 패딩
    ; ------------------------------------------------------------------------
    ds 0020h - $, 0

IMG_START:              ; 정확히 0020H 번지에 위치함